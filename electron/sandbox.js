// WSL Linux sandbox — the agent's "on its computer" box, mirroring the
// original's cloud SandBox service with local device storage instead.
//
// Model (per the OmniRush REA): a settings-card setup flow with an explicit
// user download step, an enable toggle, one-time provisioning, graceful
// fallback to the host while the sandbox is not ready, and a reset action.
//
// States:
//   missing-wsl    — WSL itself is not installed (offer: wsl --install)
//   no-distro      — WSL installed, no distro registered (offer: install Ubuntu)
//   ready          — a distro is registered and boots
//   error          — probe failed
//
// Security contract:
//   - this module spawns nothing of its own: every WSL invocation is a
//     generated one-line PowerShell script executed through the trusted
//     shell-runner (script text → 0600 temp file → executed by absolute
//     path — the same contract as every other approved command).
//   - distro names and generated script paths are charset-validated before
//     they are embedded in a generated script (no quotes, no metacharacters).
//   - agent scripts pass the same user-approval gate as local commands; the
//     script is persisted to a boundary-checked 0600 temp file and executed
//     by translated path — script text never enters any argument vector.

const crypto = require("node:crypto");
const fs = require("node:fs");
const fsp = require("node:fs/promises");
const os = require("node:os");
const path = require("node:path");
const { runShellScript } = require("./shell-runner");

const MARKER = "emberling-sandbox-ready";
const MAX_SCRIPT_LEN = 8000;

// Distro names: letters, digits, dash, underscore, dot, spaces (e.g. "Ubuntu-22.04").
// The strict charset guarantees nothing metacharacter-like reaches a script line.
const DISTRO_RE = /^[A-Za-z0-9._\- ]{1,64}$/;

// Script paths are generated by this module: real temp root + fixed prefix + UUID.
const WIN_SCRIPT_RE = /^[A-Za-z]:\\[^\\]+\\(?:[^\\]+\\)*emberling-sandbox-[0-9a-f-]{36}\.sh$/;

function validateDistro(name) {
  const s = String(name || "").trim();
  if (!DISTRO_RE.test(s)) throw new Error("invalid distro name: " + s.slice(0, 40));
  return s;
}

// Run one wsl.exe line through the trusted local runner. UTF-8 is forced so
// wsl's UTF-16 console output arrives as clean text.
async function wsl(psCommand, { timeoutMs, signal } = {}) {
  const controller = new AbortController();
  let timedOut = false;
  const timer = setTimeout(() => {
    timedOut = true;
    controller.abort();
  }, timeoutMs || 30000);
  if (signal) {
    if (signal.aborted) {
      clearTimeout(timer);
      throw Object.assign(new Error("aborted"), { name: "AbortError" });
    }
    signal.addEventListener("abort", () => controller.abort(), { once: true });
  }
  try {
    const script =
      "$ErrorActionPreference='Stop';" +
      "[Console]::OutputEncoding=[System.Text.Encoding]::UTF8;" +
      // wsl.exe emits UTF-16LE when redirected, which PowerShell would decode
      // as mojibake — WSL_UTF8=1 (documented) forces clean UTF-8 output
      "$env:WSL_UTF8='1';" +
      psCommand;
    return await runShellScript({ script, signal: controller.signal });
  } catch (err) {
    if (timedOut) {
      return { exitCode: null, stdout: "", stderr: "wsl timed out" };
    }
    throw err;
  } finally {
    clearTimeout(timer);
  }
}

function wslAvailable() {
  return fs.existsSync("C:\\Windows\\System32\\wsl.exe");
}

async function listDistros() {
  if (!wslAvailable()) return [];
  const r = await wsl("wsl.exe --list --quiet", { timeoutMs: 20000 });
  if (r.exitCode !== 0) return [];
  return r.stdout
    .split(/\r?\n/)
    .map((s) => s.trim())
    .filter((s) => s && DISTRO_RE.test(s));
}

async function probe() {
  if (!wslAvailable()) {
    return { state: "missing-wsl", distros: [], distro: null, hint: "WSL is not installed on this PC." };
  }
  const distros = await listDistros();
  if (!distros.length) {
    return { state: "no-distro", distros, distro: null, hint: "WSL is installed but no Linux distribution is registered yet." };
  }
  // prefer a distro the app installed, else the first registered one
  const distro = validateDistro(distros.find((d) => /ubuntu|debian|emberling/i.test(d)) || distros[0]);
  const boot = await wsl("wsl.exe -d " + distro + " -- echo " + MARKER, { timeoutMs: 30000 });
  if (boot.exitCode === 0 && boot.stdout.includes(MARKER)) {
    return { state: "ready", distros, distro, hint: null };
  }
  const detail = [boot.stderr, boot.stdout, "distro did not answer"].find((s) => s && s.trim()) || "";
  return { state: "error", distros, distro, hint: detail.slice(0, 200) };
}

// Kick off the OS-level install. `wsl --install` needs elevation; the
// generated script elevates via Start-Process -Verb RunAs (Windows shows the
// UAC prompt). Progress is tracked by polling probe().
async function install() {
  if (!wslAvailable()) {
    await wsl("Start-Process wsl.exe -ArgumentList '--install','-d','Ubuntu' -Verb RunAs", { timeoutMs: 60000 });
    return { ok: true, note: "WSL installation started — accept the Windows prompt; a restart may be required. Check status in a minute." };
  }
  const distros = await listDistros();
  if (distros.length) {
    return { ok: true, note: ["A Linux distribution is already registered:", distros.join(", ")].join(" ") };
  }
  const r = await wsl("wsl.exe --install -d Ubuntu --no-launch", { timeoutMs: 600000 });
  const note = r.exitCode === 0
    ? "Linux distribution download started — check status in a minute."
    : ["Installer exited with", String(r.exitCode), (r.stderr || r.stdout || "").slice(0, 200)].join(" ");
  return { ok: true, note };
}

// Remove the distro (reset). Requires explicit user confirmation upstream.
async function reset(distroName) {
  const distros = await listDistros();
  const target = validateDistro(distroName || distros.find((d) => /ubuntu|debian|emberling/i.test(d)) || distros[0]);
  if (!distros.includes(target)) return { ok: false, error: "distro is not registered: " + target };
  const r = await wsl("wsl.exe --unregister " + target, { timeoutMs: 60000 });
  const detail = [r.stderr, r.stdout].join(" ").slice(0, 200);
  return { ok: r.exitCode === 0, note: r.exitCode === 0 ? [target, "unregistered"].join(" ") : detail };
}

/* ---------- per-Dotling VMs ----------
 * Each agent (Dotling) gets its own private WSL distro, cloned lazily from
 * the base image on first use — no per-bot download. Cloning = wsl --export
 * the base to a temp tar + wsl --import under the bot's own name and install
 * directory, so filesystems stay fully isolated between Dotlings. Commands
 * inside a Dotling's VM need no user approval: the VM boundary is the
 * security control (the same reasoning as the original's cloud box). */

// Fixed literal base for per-bot install directories.
const VM_DIR_BASE = "C:\\Users\\Public\\emberling-wsl";
// scope ids come from agent-store scopeId: [a-z0-9-]{1,48}
const SCOPE_RE = /^[a-z0-9-]{1,48}$/;

function scopeDistroName(scope) {
  const s = String(scope || "").trim().toLowerCase();
  if (!SCOPE_RE.test(s)) throw new Error("invalid sandbox scope: " + s.slice(0, 40));
  const name = "emberling-" + s;
  if (!DISTRO_RE.test(name)) throw new Error("invalid distro name: " + name.slice(0, 40));
  return name;
}

async function ensureScopeDistro(scope) {
  const name = scopeDistroName(scope);
  // dispatch through module.exports so tests can stub the WSL surface
  const distros = await module.exports.listDistros();
  if (distros.includes(name)) return name;
  // need a ready base image to clone from
  const base = await module.exports.probe();
  if (base.state !== "ready") return null;
  // export the base to a boundary-checked temp tar, then import per scope.
  // NOTE: --export/--import file arguments are interpreted by the WINDOWS-side
  // wsl.exe — they must be Windows paths, quoted, with the parent directory
  // created first (--import does not create parent chains).
  const tmpRoot = fs.realpathSync(os.tmpdir());
  const tarPath = path.resolve(tmpRoot, "emberling-sandbox-" + crypto.randomUUID() + ".tar");
  if (!tarPath.startsWith(tmpRoot + path.sep)) throw new Error("clone tar escaped the temp directory");
  const installDir = VM_DIR_BASE + "\\" + scope;
  if (!/^[A-Za-z]:\\Users\\Public\\emberling-wsl\\[a-z0-9-]{1,48}$/.test(installDir)) {
    throw new Error("clone install dir failed validation");
  }
  fs.mkdirSync(VM_DIR_BASE, { recursive: true });
  try {
    const exp = await wsl("wsl.exe --export " + base.distro + " '" + tarPath + "'", { timeoutMs: 600000 });
    if (exp.exitCode !== 0) {
      return null;
    }
    const imp = await wsl(
      "wsl.exe --import " + name + " '" + installDir + "' '" + tarPath + "'",
      { timeoutMs: 600000 }
    );
    if (imp.exitCode !== 0) {
      return null;
    }
    const verify = await wsl("wsl.exe -d " + name + " -- echo " + MARKER, { timeoutMs: 60000 });
    return verify.exitCode === 0 && verify.stdout.includes(MARKER) ? name : null;
  } finally {
    fsp.unlink(tarPath).catch(() => {});
  }
}

/* ---------- path translation ---------- */

function winToWslPath(p) {
  if (typeof p !== "string" || !p.trim()) return p;
  if (/^[a-zA-Z]:[\\/]/.test(p)) {
    const drive = p[0].toLowerCase();
    const rest = p.slice(2).replace(/\\/g, "/").replace(/\/+$/, "");
    return "/mnt/" + drive + rest;
  }
  return p;
}

function wslToWinPath(p) {
  const m = typeof p === "string" ? p.match(/^\/mnt\/([a-zA-Z])(\/.*)?$/) : null;
  if (!m) return p;
  return m[1].toUpperCase() + ":" + ((m[2] || "").replace(/\//g, "\\") || "\\");
}

// True when the argument is a Windows-absolute path that must be translated.
function isWinAbsPath(p) {
  return typeof p === "string" && /^[a-zA-Z]:[\\/]/.test(p);
}

// POSIX single-quote escaping for embedding a path inside a bash script line.
// Distros/paths here are charset-validated upstream; this is belt-and-braces.
function shQuote(p) {
  return "'" + String(p).replace(/'/g, `'\\''`) + "'";
}

// Boundary-checked temp file used to bridge bytes across the WSL boundary
// (write: local file → `cp` to target; read: `cat` target → local file).
async function tempBridgeFile() {
  const tmpRoot = fs.realpathSync(os.tmpdir());
  const hostPath = path.resolve(tmpRoot, "emberling-sandbox-" + crypto.randomUUID() + ".tmp");
  if (!hostPath.startsWith(tmpRoot + path.sep)) {
    throw new Error("bridge path escaped the temp directory");
  }
  return {
    hostPath,
    wslPath: winToWslPath(hostPath),
    cleanup: () => fsp.unlink(hostPath).catch(() => {}),
  };
}

/**
 * Run a shell script inside the sandbox distro. The script has already passed
 * auto-review (user deny rules); execution inside a Dotling's VM requires no
 * approval prompt — the VM boundary is the security control. Following the
 * local shell-runner contract: the script is persisted to a 0600 temp file
 * inside the OS temp dir (boundary-checked) and executed by translated path —
 * script text never enters any argument vector.
 */
async function runInSandbox({ script, cwd, scope, distro, timeoutMs, signal }) {
  if (!wslAvailable()) throw new Error("WSL is not installed");
  if (typeof script !== "string" || !script.trim()) throw new Error("empty script");
  if (script.length > MAX_SCRIPT_LEN) throw new Error("script too long for sandbox");

  // distro resolution: explicit override > per-Dotling clone > shared base
  let effectiveDistro = null;
  if (distro) {
    effectiveDistro = validateDistro(distro);
  } else if (scope) {
    effectiveDistro = await ensureScopeDistro(scope);
    if (!effectiveDistro) throw new Error("Linux sandbox is not ready — no base distribution to clone from");
  } else {
    effectiveDistro = validateDistro((await module.exports.probe()).distro);
  }
  if (!effectiveDistro) throw new Error("no Linux distribution registered");

  // optional working directory: a cd prefix, single-quoted (shQuote)
  let scriptText = typeof script === "string" ? script : "";
  if (cwd && typeof cwd === "string" && cwd.trim()) {
    scriptText = "cd " + shQuote(winToWslPath(cwd.trim())) + " 2>/dev/null || true\n" + scriptText;
  }

  // temp dir boundary: resolve the real root and confirm the target stays inside
  const tmpRoot = fs.realpathSync(os.tmpdir());
  const hostPath = path.resolve(tmpRoot, "emberling-sandbox-" + crypto.randomUUID() + ".sh");
  if (!hostPath.startsWith(tmpRoot + path.sep)) {
    throw new Error("sandbox script path escaped the temp directory");
  }
  await fsp.writeFile(hostPath, scriptText, { mode: 0o600 });
  try {
    const scriptPath = winToWslPath(hostPath);
    if (!/^\/mnt\/[a-z]\/[^ ]*\/emberling-sandbox-[0-9a-f-]{36}\.sh$/.test(scriptPath)) {
      throw new Error("sandbox script path failed validation");
    }
    const r = await wsl("wsl.exe -d " + effectiveDistro + " -- /bin/bash " + scriptPath, {
      timeoutMs: timeoutMs || 120000,
      signal,
    });
    if (/wsl timed out/.test(r.stderr || "")) {
      return { exitCode: null, stdout: r.stdout.slice(0, 6000), stderr: (r.stderr + "\n[sandbox] timed out").slice(0, 3000), sandbox: effectiveDistro };
    }
    return {
      exitCode: r.exitCode,
      stdout: r.stdout.length > 6000 ? r.stdout.slice(0, 6000) + "\n… [truncated " + (r.stdout.length - 6000) + " chars]" : r.stdout,
      stderr: r.stderr.length > 3000 ? r.stderr.slice(0, 3000) + "\n… [truncated " + (r.stderr.length - 3000) + " chars]" : r.stderr,
      sandbox: effectiveDistro,
    };
  } finally {
    fsp.unlink(hostPath).catch(() => {});
  }
}

module.exports = {
  wslAvailable,
  probe,
  install,
  reset,
  listDistros,
  runInSandbox,
  ensureScopeDistro,
  scopeDistroName,
  tempBridgeFile,
  shQuote,
  winToWslPath,
  wslToWinPath,
  isWinAbsPath,
  MARKER,
};
